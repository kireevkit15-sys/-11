FONT_BODY = "Calibri"
FONT_HEADING = "Calibri"

COLOR_TEXT = RGBColor(0x1F, 0x1F, 0x1F)
COLOR_MUTED = RGBColor(0x55, 0x55, 0x55)
COLOR_HEADING = RGBColor(0x0F, 0x2D, 0x52)
COLOR_TABLE_HEADER_BG = "E9EDF3"
COLOR_TABLE_BORDER = "B8C0CC"


def set_cell_bg(cell, hex_color: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tc_pr.append(shd)


def set_cell_borders(cell, color: str = COLOR_TABLE_BORDER, sz: str = "4") -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_borders = OxmlElement("w:tcBorders")
    for side in ("top", "left", "bottom", "right"):
        b = OxmlElement(f"w:{side}")
        b.set(qn("w:val"), "single")
        b.set(qn("w:sz"), sz)
        b.set(qn("w:color"), color)
        tc_borders.append(b)
    tc_pr.append(tc_borders)


def set_paragraph_spacing(p, before: int = 0, after: int = 6, line: float = 1.25) -> None:
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line


def add_title(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    set_paragraph_spacing(p, before=0, after=4, line=1.15)
    run = p.add_run(text)
    run.font.name = FONT_HEADING
    run.font.size = Pt(22)
    run.font.bold = True
    run.font.color.rgb = COLOR_HEADING


def add_subtitle(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    set_paragraph_spacing(p, before=0, after=18, line=1.2)
    run = p.add_run(text)
    run.font.name = FONT_BODY
    run.font.size = Pt(12)
    run.font.color.rgb = COLOR_MUTED


def add_h1(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    set_paragraph_spacing(p, before=18, after=8, line=1.2)
    run = p.add_run(text)
    run.font.name = FONT_HEADING
    run.font.size = Pt(15)
    run.font.bold = True
    run.font.color.rgb = COLOR_HEADING


def add_h2(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    set_paragraph_spacing(p, before=12, after=4, line=1.2)
    run = p.add_run(text)
    run.font.name = FONT_HEADING
    run.font.size = Pt(12)
    run.font.bold = True
    run.font.color.rgb = COLOR_TEXT


def add_para(doc: Document, text: str, *, after: int = 8) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    set_paragraph_spacing(p, after=after, line=1.3)
    run = p.add_run(text)
    run.font.name = FONT_BODY
    run.font.size = Pt(11)
    run.font.color.rgb = COLOR_TEXT


def add_table(doc: Document, headers: list[str], rows: list[list[str]], col_widths_cm: list[float]) -> None:
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.autofit = False
    table.allow_autofit = False

    for i, w in enumerate(col_widths_cm):
        for cell in table.columns[i].cells:
            cell.width = Cm(w)

    header_cells = table.rows[0].cells
    for i, text in enumerate(headers):
        cell = header_cells[i]
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        set_cell_bg(cell, COLOR_TABLE_HEADER_BG)
        set_cell_borders(cell)
        cell.text = ""
        p = cell.paragraphs[0]
        set_paragraph_spacing(p, before=4, after=4, line=1.15)
        r = p.add_run(text)
        r.font.name = FONT_HEADING
        r.font.size = Pt(10.5)
        r.font.bold = True
        r.font.color.rgb = COLOR_HEADING

    for row_idx, row in enumerate(rows, start=1):
        for col_idx, text in enumerate(row):
            cell = table.rows[row_idx].cells[col_idx]
            cell.vertical_alignment = WD_ALIGN_VERTICAL.TOP
            set_cell_borders(cell)
            cell.text = ""
            p = cell.paragraphs[0]
            set_paragraph_spacing(p, before=3, after=3, line=1.25)
            r = p.add_run(text)
            r.font.name = FONT_BODY
            r.font.size = Pt(10.5)
            r.font.color.rgb = COLOR_TEXT


def add_signature_block(doc: Document) -> None:
    p = doc.add_paragraph()
    set_paragraph_spacing(p, before=24, after=4, line=1.3)
    r = p.add_run("С уважением,")
    r.font.name = FONT_BODY
    r.font.size = Pt(11)

    p = doc.add_paragraph()
    set_paragraph_spacing(p, after=4)
    r = p.add_run("Команда разработки сайта")
    r.font.name = FONT_BODY
    r.font.size = Pt(11)
    r.font.bold = True

    p = doc.add_paragraph()
    set_paragraph_spacing(p, after=0)
    r = p.add_run("Контакты для оперативной связи: __________________")
    r.font.name = FONT_BODY
    r.font.size = Pt(11)
    r.font.color.rgb = COLOR_MUTED


