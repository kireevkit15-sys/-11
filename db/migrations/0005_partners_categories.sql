-- =====================================================================
-- ДИВА — миграция 0005: добавление categories (jsonb) в partners.
--
-- Зачем: на /announcements нужны кликабельные фильтры по категориям
-- («Разработка сайтов», «Разработка мобильных приложений» и т.д.).
-- Старая колонка category — single enum (fullstack/mobile/ai/...),
-- она не совпадает с пользовательским списком и остаётся для
-- внутренних нужд. Новая categories — jsonb-массив строк из фикса
-- partnerTags (web/src/data/partners.ts). Партнёр может принадлежать
-- нескольким категориям сразу.
--
-- Идемпотентность: ADD COLUMN IF NOT EXISTS. DEFAULT '[]'::jsonb —
-- все существующие строки получают пустой массив (партнёр виден во
-- «все», ни в одном фильтре не отсекается).
-- =====================================================================

ALTER TABLE partners
  ADD COLUMN IF NOT EXISTS categories jsonb NOT NULL DEFAULT '[]'::jsonb;
