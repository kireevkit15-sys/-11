-- =====================================================================
-- ДИВА — миграция 0004: добавление image_url в announcements.
--
-- Зачем: админ-форма для объявлений требует загрузки обложки (фото/баннер),
-- но в исходной схеме поле image_url отсутствует. Без него нельзя ни
-- сохранить URL, ни отобразить фото в карточке объявления на сайте.
--
-- Безопасное добавление nullable колонки: PostgreSQL не переписывает
-- таблицу при добавлении nullable-полей в большинстве случаев (с версии
-- 11). IF NOT EXISTS гарантирует идемпотентность.
-- =====================================================================

ALTER TABLE announcements
  ADD COLUMN IF NOT EXISTS image_url text;

-- Для совместимости с другими image-полями в схеме (client_logo_url,
-- cover_url, thumbnail_url) держим snake_case, как и в остальных миграциях.
