/** Декодирует байты как cp1251 → JS string (unicode). */
function decodeCp1251(bytes: Uint8Array): string {
  let out = '';
  for (let i = 0; i < bytes.length; i++) {
    const byteVal = bytes[i] ?? 0;
    if (byteVal < 0x80) {
      out += String.fromCharCode(byteVal);
    } else {
      const cp = CP1251[byteVal];
      out += String.fromCharCode(cp ?? 0xFFFD);
    }
  }
  return out;
}

/** TextDecoder для cp1251 (Node 16+). */
let cp1251Decoder: TextDecoder | null = null;
function getCp1251Decoder(): TextDecoder {
  if (!cp1251Decoder) {
    cp1251Decoder = new TextDecoder('windows-1251');
  }
  return cp1251Decoder;
}

function tryParseJson(s: string): unknown {
  try {
    return JSON.parse(s);
  } catch {
    return undefined;
  }
}

/**
 * Читает тело запроса с авто-детектом кодировки (UTF-8 → cp1251).
 * Возвращает распарсенный JSON или undefined, если ни одна кодировка не дала валидный JSON.
 */
export async function readJsonBody<T = unknown>(req: Request): Promise<T | undefined> {
  // 1) UTF-8
  const utf8Text = await req.text();
  const utf8Parsed = tryParseJson(utf8Text);
  if (utf8Parsed !== undefined) return utf8Parsed;

  // 2) cp1251 fallback
  try {
    const buf = new Uint8Array(await req.arrayBuffer());
    const cp1251Text = getCp1251Decoder().decode(buf);
    const cpParsed = tryParseJson(cp1251Text);
    if (cpParsed !== undefined) return cpParsed;

    // 3) Ручной декодер (на случай если TextDecoder неожиданно упал)
    const manualText = decodeCp1251(buf);
    const manualParsed = tryParseJson(manualText);
    return manualParsed;
  } catch {
    return undefined;
  }
}

/** Прямой декодер cp1251 из bytes (для тестов и одноразовых вызовов). */
export function decodeCp1251FromBytes(bytes: Uint8Array): string {
  return decodeCp1251(bytes);
}